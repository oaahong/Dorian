#!/usr/bin/env node
/**
 * Turns the skill pipeline's manifest into a table the client can read.
 *
 * `audit/skill-assets/skill-asset-manifest.json` is 163 KB of crop rectangles,
 * SHA-256 digests and source-sheet names — everything needed to *regenerate* the
 * art and nothing the browser needs at runtime. All the client wants to know is
 * which cells a fighter has, so it can ask the loader for them.
 *
 * Generating rather than hand-maintaining is the point: the manifest is written by
 * `scripts/extract_skill_assets.py`, so a new cell appears there first. Typing the
 * list a second time is a drift waiting to happen, and the drift is silent — a
 * missing entry is an asset that never loads and a texture that never draws.
 *
 * `src/fighters/__tests__/skillCells.test.ts` reads the manifest itself and fails
 * if this output has fallen behind it.
 *
 *   npm run assets:skills:codegen
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'audit', 'skill-assets', 'skill-asset-manifest.json');
const OUTPUT = join(ROOT, 'src', 'fighters', 'skillCells.ts');

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));

const entries = Object.entries(manifest.fighters)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([fighterId, entry]) => {
    const cells = [...entry.assets, ...(entry.derivedAssets ?? [])].map((asset) => asset.poseId);
    return `  ${fighterId}: [${cells.map((cell) => `'${cell}'`).join(', ')}],`;
  });

const total = Object.values(manifest.fighters).reduce(
  (sum, entry) => sum + entry.assets.length + (entry.derivedAssets?.length ?? 0),
  0,
);

writeFileSync(
  OUTPUT,
  `/**
 * Which skill-sheet cells each fighter has.
 *
 * GENERATED by \`scripts/gen-skill-cells.mjs\` from
 * \`audit/skill-assets/skill-asset-manifest.json\`. Do not edit by hand — rerun
 * \`npm run assets:skills:codegen\` after regenerating the art.
 *
 * Cells are letters because the source sheets are grids and the pipeline names
 * them by position. What each letter *is* differs per fighter — \`A\`-\`C\` are
 * always the three charge frames and \`D\` the release, but past that a cell may be
 * a pose, a standalone effect layer, or in blade's case a weapon split out of a
 * larger cell. \`src/fighters/ultimateVisuals.ts\` and \`installPoses.ts\` are where
 * the meaning is assigned.
 *
 * ${total} cells across ${entries.length} fighters.
 */
export const SKILL_CELLS: Record<string, readonly string[]> = {
${entries.join('\n')}
};
`,
  'utf8',
);

console.log(`skillCells.ts: ${total} cells across ${entries.length} fighters`);
